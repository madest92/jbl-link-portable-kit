// Тайминги подобраны на колонке.
type timing struct {
	Guard      time.Duration // столько после отмены речь Алисы отменяется повторно
	NoticeWait time.Duration // пауза перед уведомлением: иначе Алиса может отбросить фрейм
	SayStart   time.Duration // речь не началась — повтор фрейма
	ShortStart time.Duration // то же для коротких фраз, без повтора
	SpeechMax  time.Duration // дольше конца речи не ждём
	Await      time.Duration // окно, в котором следующая фраза — наша
	WarmMax    time.Duration // срок годности заранее открытого соединения
	IOHubHold  time.Duration // удержание соединения с 9910: раньше — RST, команда теряется
	Reconnect  time.Duration // пауза перед переподключением к 9875
}

